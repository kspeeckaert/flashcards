// Flashcards build script. README.md, section "Build script", explains when and how to run it.
//
// What it does:
//   1. Copies the browser libraries and web fonts from node_modules/ into vendor/.
//   2. Writes vendor/fonts/fonts.css with the @font-face rules for those fonts.
//   3. Writes the list of files that the service worker caches for offline use into sw.js,
//      together with the app version (from js/version.js) and a hash of the file contents.
//      A changed sw.js makes installed apps update.
//
// Usage:
//   bun install       once, and after a change to package.json
//   bun run build     update vendor/ and sw.js
//   bun run check     report whether vendor/ or sw.js is out of date (exit code 1); changes nothing
//
// The script uses only Node.js built-in modules, so `node scripts/build.js` works too.

import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT         = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const NODE_MODULES = path.join(ROOT, 'node_modules');
const VENDOR_DIR   = 'vendor';
const SW_FILE      = 'sw.js';
const VERSION_FILE = 'js/version.js';

// ── Libraries: [source in node_modules/, destination in vendor/] ─────────────
const LIBRARIES = [
  ['marked/lib/marked.umd.js',              'marked/marked.umd.js'],
  ['marked/LICENSE',                        'marked/LICENSE'],
  ['dompurify/dist/purify.min.js',          'dompurify/purify.min.js'],
  ['dompurify/LICENSE',                     'dompurify/LICENSE'],
  ['katex/dist/katex.min.js',               'katex/katex.min.js'],
  ['katex/dist/katex.min.css',              'katex/katex.min.css'],
  ['katex/dist/contrib/auto-render.min.js', 'katex/contrib/auto-render.min.js'],
  ['katex/LICENSE',                         'katex/LICENSE'],
  ['mermaid/dist/mermaid.min.js',           'mermaid/mermaid.min.js'],
  ['mermaid/LICENSE',                       'mermaid/LICENSE'],
];

// KaTeX fonts: only .woff2. katex.min.css lists woff2 first, and every supported browser
// reads woff2, so the .woff and .ttf files are never requested.
const KATEX_FONTS_SRC  = 'katex/dist/fonts';
const KATEX_FONTS_DEST = 'katex/fonts';

// ── Web fonts (Fontsource) ───────────────────────────────────────────────────
// Only the latin and latin-ext subsets. Other scripts (for example Japanese) use system fonts.
// The unicode ranges are copied from the Fontsource 5.3.0 CSS files.
const FONT_SUBSETS = {
  'latin-ext': 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF',
  'latin':     'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
};
const FONTS = [
  { family: 'Lora',    pkg: '@fontsource/lora',    id: 'lora',    weight: 400, style: 'normal' },
  { family: 'Lora',    pkg: '@fontsource/lora',    id: 'lora',    weight: 600, style: 'normal' },
  { family: 'Lora',    pkg: '@fontsource/lora',    id: 'lora',    weight: 400, style: 'italic' },
  { family: 'DM Sans', pkg: '@fontsource/dm-sans', id: 'dm-sans', weight: 300, style: 'normal' },
  { family: 'DM Sans', pkg: '@fontsource/dm-sans', id: 'dm-sans', weight: 400, style: 'normal' },
  { family: 'DM Sans', pkg: '@fontsource/dm-sans', id: 'dm-sans', weight: 500, style: 'normal' },
];
const FONT_LICENSES = [
  ['@fontsource/lora/LICENSE',    'fonts/LICENSE-Lora'],
  ['@fontsource/dm-sans/LICENSE', 'fonts/LICENSE-DM-Sans'],
];

// ── Precache: files the service worker stores for offline use ────────────────
const PRECACHE_FILES = ['flashcards.html', 'img-to-md.html', 'manifest.webmanifest'];
const PRECACHE_DIRS  = ['css', 'js', 'img', 'vendor'];
const precacheSkip   = name => name === '.DS_Store' || name.startsWith('LICENSE') || name.endsWith('.map');

const BLOCK_BEGIN = '// BEGIN PRECACHE (generated by scripts/build.js, do not edit)';
const BLOCK_END   = '// END PRECACHE';

// ── Helpers ──────────────────────────────────────────────────────────────────
const toUrlPath = rel => rel.split(path.sep).join('/');
const sha256    = data => createHash('sha256').update(data).digest('hex');

async function walk(dirAbs) {
  if (!existsSync(dirAbs)) return [];
  const out = [];
  for (const entry of await readdir(dirAbs, { withFileTypes: true })) {
    const abs = path.join(dirAbs, entry.name);
    if (entry.isDirectory()) out.push(...await walk(abs));
    else if (entry.isFile()) out.push(abs);
  }
  return out;
}

// Returns Map<path relative to vendor/ (URL style), Buffer> with every file vendor/ must contain.
async function expectedVendorFiles() {
  if (!existsSync(NODE_MODULES)) {
    throw new Error('node_modules/ is missing. Run "bun install" first.');
  }
  const files = new Map();
  const read  = async (src, dest) => files.set(dest, await readFile(path.join(NODE_MODULES, src)));

  for (const [src, dest] of [...LIBRARIES, ...FONT_LICENSES]) await read(src, dest);

  for (const name of (await readdir(path.join(NODE_MODULES, KATEX_FONTS_SRC))).sort()) {
    if (name.endsWith('.woff2')) await read(`${KATEX_FONTS_SRC}/${name}`, `${KATEX_FONTS_DEST}/${name}`);
  }

  const css = ['/* Generated by scripts/build.js from Fontsource packages. Do not edit. */'];
  for (const f of FONTS) {
    for (const [subset, range] of Object.entries(FONT_SUBSETS)) {
      const file = `${f.id}-${subset}-${f.weight}-${f.style}.woff2`;
      await read(`${f.pkg}/files/${file}`, `fonts/${file}`);
      css.push(
        '@font-face {',
        `  font-family: '${f.family}';`,
        `  font-style: ${f.style};`,
        `  font-weight: ${f.weight};`,
        '  font-display: swap;',
        `  src: url(./${file}) format('woff2');`,
        `  unicode-range: ${range};`,
        '}',
      );
    }
  }
  files.set('fonts/fonts.css', Buffer.from(css.join('\n') + '\n'));
  return files;
}

async function appVersion() {
  const src   = await readFile(path.join(ROOT, VERSION_FILE), 'utf8');
  const match = src.match(/const APP_VERSION\s*=\s*'([^']+)'/);
  if (!match) throw new Error(`No "const APP_VERSION = '...'" line in ${VERSION_FILE}.`);
  return match[1];
}

// Returns { version, urls, hash } for the files on disk that the service worker must precache.
async function precacheManifest() {
  const abs = [];
  for (const f of PRECACHE_FILES) {
    const p = path.join(ROOT, f);
    if (!existsSync(p)) throw new Error(`Precache file is missing: ${f}`);
    abs.push(p);
  }
  for (const d of PRECACHE_DIRS) abs.push(...await walk(path.join(ROOT, d)));

  const urls = abs
    .filter(p => !precacheSkip(path.basename(p)))
    .map(p => toUrlPath(path.relative(ROOT, p)))
    .sort();

  const h = createHash('sha256');
  for (const url of urls) h.update(`${url}\0${sha256(await readFile(path.join(ROOT, url)))}\n`);
  return { version: await appVersion(), urls, hash: h.digest('hex').slice(0, 12) };
}

function renderBlock({ version, urls, hash }) {
  return [
    BLOCK_BEGIN,
    `const APP_VERSION = '${version}';`,
    `const BUILD_HASH = '${hash}';`,
    'const PRECACHE_URLS = [',
    ...urls.map(u => `  '${u}',`),
    '];',
    BLOCK_END,
  ].join('\n');
}

function replaceBlock(swSource, block) {
  const start = swSource.indexOf(BLOCK_BEGIN);
  const end   = swSource.indexOf(BLOCK_END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`${SW_FILE} has no "${BLOCK_BEGIN}" ... "${BLOCK_END}" block.`);
  }
  return swSource.slice(0, start) + block + swSource.slice(end + BLOCK_END.length);
}

// ── Commands ─────────────────────────────────────────────────────────────────
async function build() {
  const vendor = await expectedVendorFiles();
  await rm(path.join(ROOT, VENDOR_DIR), { recursive: true, force: true });
  for (const [rel, data] of vendor) {
    const dest = path.join(ROOT, VENDOR_DIR, rel);
    await mkdir(path.dirname(dest), { recursive: true });
    await writeFile(dest, data);
  }

  const manifest = await precacheManifest();
  const swPath   = path.join(ROOT, SW_FILE);
  await writeFile(swPath, replaceBlock(await readFile(swPath, 'utf8'), renderBlock(manifest)));

  console.log(`vendor/: ${vendor.size} files`);
  console.log(`${SW_FILE}: version ${manifest.version}, ${manifest.urls.length} files to precache, build hash ${manifest.hash}`);
}

async function check() {
  const problems = [];

  const vendor = await expectedVendorFiles();
  const onDisk = new Set(
    (await walk(path.join(ROOT, VENDOR_DIR))).map(p => toUrlPath(path.relative(path.join(ROOT, VENDOR_DIR), p)))
  );
  for (const [rel, data] of vendor) {
    const p = path.join(ROOT, VENDOR_DIR, rel);
    if (!onDisk.has(rel)) problems.push(`missing:  vendor/${rel}`);
    else if (!data.equals(await readFile(p))) problems.push(`outdated: vendor/${rel}`);
    onDisk.delete(rel);
  }
  for (const rel of onDisk) problems.push(`extra:    vendor/${rel}`);

  const swSource = await readFile(path.join(ROOT, SW_FILE), 'utf8');
  if (replaceBlock(swSource, renderBlock(await precacheManifest())) !== swSource) {
    problems.push(`outdated: ${SW_FILE} precache list or build hash`);
  }

  if (problems.length) {
    console.error(problems.join('\n'));
    console.error('\nRun "bun run build" to fix this.');
    process.exit(1);
  }
  console.log('vendor/ and sw.js are up to date.');
}

try {
  await (process.argv.includes('--check') ? check() : build());
} catch (err) {
  console.error(`Error: ${err.message}`);
  process.exit(1);
}
